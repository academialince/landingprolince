### La Casa del Rey (art. 65)

El Rey recibe de los Presupuestos del Estado una **cantidad global** para el sostenimiento de su Familia y Casa, y la **distribuye libremente**. Nombra y releva libremente a los miembros civiles y militares de su Casa.

## Las Cortes Generales (arts. 66 a 96)

### Qué son (art. 66)

- **Representan al pueblo español** y están formadas por el **Congreso de los Diputados** y el **Senado**.
- Ejercen la **potestad legislativa**, aprueban los **Presupuestos**, **controlan la acción del Gobierno** y tienen las demás competencias que les atribuye la Constitución.
- Son **inviolables**.

### Congreso de los Diputados (art. 68)

| Dato | Valor |
|---|---|
| Composición | Mínimo **300**, máximo **400** Diputados (la ley electoral fija hoy 350) |
| Elección | Sufragio universal, libre, igual, directo y secreto |
| Circunscripción | La **provincia**; **Ceuta y Melilla**, un Diputado cada una |
| Reparto | Representación mínima inicial por circunscripción y el resto en proporción a la población |
| Sistema | Criterios de representación **proporcional** |
| Mandato | **Cuatro años**, o hasta la disolución |
| Elecciones | Entre **30 y 60 días** desde la terminación del mandato |
| Constitución | El Congreso electo se convoca dentro de los **25 días** siguientes a las elecciones |

### Senado (art. 69)

- Es la **Cámara de representación territorial**.
- **Cuatro Senadores por provincia**, por sufragio universal, libre, igual, directo y secreto.
- **Provincias insulares:** cada isla con Cabildo o Consejo Insular es una circunscripción. **Tres** Senadores para cada isla mayor (Gran Canaria, Mallorca y Tenerife) y **uno** para cada una de estas: **Ibiza, Formentera**, Menorca, Fuerteventura, La Gomera, El Hierro, Lanzarote y La Palma.
- **Ceuta y Melilla:** **dos** Senadores cada una.
- **Comunidades Autónomas:** designan **un Senador** y otro más **por cada millón de habitantes**, a través de su Asamblea legislativa (o su órgano colegiado superior), con adecuada representación proporcional.
- Mandato de **cuatro años**.

**Ojo a la reforma de 2026:** el texto original agrupaba «Ibiza-Formentera» en una sola circunscripción. La Reforma de 19 de mayo de 2026 las separa, pero su eficacia queda **pospuesta hasta las primeras elecciones al Senado** que se convoquen tras su entrada en vigor. Si estudias con un manual antiguo, corrígelo.

### Estatuto de los parlamentarios (arts. 67, 70 y 71)

- Nadie puede ser miembro de las dos Cámaras a la vez, ni acumular el acta de una Asamblea autonómica con la de Diputado (67.1).
- **No están ligados por mandato imperativo** (67.2).
- **Inelegibilidad e incompatibilidad** (70.1): alcanza, entre otros, a los miembros del Tribunal Constitucional, el Defensor del Pueblo, los Magistrados, Jueces y Fiscales en activo, y **los militares profesionales y miembros de las Fuerzas y Cuerpos de Seguridad y Policía en activo**. Es un dato que te afecta directamente.
- **Inviolabilidad** por las opiniones manifestadas en el ejercicio de sus funciones (71.1).
- **Inmunidad**: solo pueden ser detenidos en caso de **flagrante delito**, y no pueden ser inculpados ni procesados sin **autorización de la Cámara** (71.2).
- **Aforamiento**: en las causas contra Diputados y Senadores es competente la **Sala de lo Penal del Tribunal Supremo** (71.3).

