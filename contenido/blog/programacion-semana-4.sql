## Casos prácticos (hipotéticos)

**Caso 1.** Un ayuntamiento quiere prohibir una concentración en la plaza mayor porque «no ha pedido permiso». *Solución:* el derecho de reunión no necesita autorización previa (21.1). En lugares de tránsito público se exige **comunicación previa**, y la autoridad solo puede prohibir la reunión si hay razones fundadas de alteración del orden público con peligro para personas o bienes (21.2).

**Caso 2.** Alguien quiere recurrir en amparo porque no le conceden una vivienda digna. *Solución:* el derecho a la vivienda (art. 47) es un principio rector del Capítulo tercero: no tiene amparo y solo puede alegarse ante los tribunales según las leyes que lo desarrollen (53.3).

**Caso 3.** Se declara el estado de alarma. ¿Puede suspenderse el derecho de huelga con base en el artículo 55.1? *Solución:* no. El 55.1 solo prevé la suspensión en los estados de excepción y de sitio.

