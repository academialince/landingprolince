### Senado (art. 69)

- Es la **Cámara de representación territorial**.
- **Cuatro Senadores por provincia**, por sufragio universal, libre, igual, directo y secreto.
- **Provincias insulares:** cada isla con Cabildo o Consejo Insular es una circunscripción. **Tres** Senadores para cada isla mayor (Gran Canaria, Mallorca y Tenerife) y **uno** para cada una de estas: **Ibiza, Formentera**, Menorca, Fuerteventura, La Gomera, El Hierro, Lanzarote y La Palma.
- **Ceuta y Melilla:** **dos** Senadores cada una.
- **Comunidades Autónomas:** designan **un Senador** y otro más **por cada millón de habitantes**, a través de su Asamblea legislativa (o su órgano colegiado superior), con adecuada representación proporcional.
- Mandato de **cuatro años**.

