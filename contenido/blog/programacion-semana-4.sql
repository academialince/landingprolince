## Respuestas explicadas

**1 (b).** Los cuatro valores superiores son libertad, justicia, igualdad y pluralismo político. La opción a) mezcla el lema de la Revolución francesa; *seguridad* y *solidaridad* no están en el artículo 1.1.

**2 (c).** «La forma política del Estado español es la Monarquía parlamentaria» (art. 1.3). El 1.2 dice que la soberanía nacional reside en el pueblo español.

**3 (b).** El castellano es la lengua oficial del Estado y todos los españoles tienen **el deber de conocerla y el derecho a usarla** (art. 3.1). Las demás lenguas son también oficiales en sus comunidades según sus Estatutos (art. 3.2).

**4 (a).** Roja, amarilla y roja, «siendo la amarilla de doble anchura que cada una de las rojas» (art. 4.1).

**5 (c).** El artículo 14 abre el Capítulo segundo del Título I. El 9 recoge, entre otros, los principios de legalidad y seguridad jurídica; el 10, la dignidad de la persona; el 15, el derecho a la vida.

**6 (b).** La pena de muerte queda abolida, «salvo lo que puedan disponer las leyes penales militares para tiempos de guerra» (art. 15). Es una pregunta de matiz: la c) parece correcta si no recuerdas la salvedad.

**7 (c).** La detención preventiva no puede durar más del tiempo estrictamente necesario y, en todo caso, **72 horas**; después, libertad o disposición judicial (art. 17.2).

**8 (b).** Ninguna entrada o registro sin consentimiento del titular o **resolución judicial**, salvo en caso de **flagrante delito** (art. 18.2). Ninguna autoridad administrativa ni policial puede suplir la resolución judicial.

**9 (b).** «Se prohíben las asociaciones secretas y las de carácter paramilitar» (art. 22.5). Las asociaciones que persigan fines o utilicen medios tipificados como delito son ilegales (art. 22.2).

**10 (c).** El artículo 28.1 permite limitar o exceptuar la sindicación de las Fuerzas o Institutos armados y los demás Cuerpos sometidos a disciplina militar. Para los funcionarios públicos, la ley solo regula **las peculiaridades** de su ejercicio, por eso la a) es incorrecta.

**11 (b).** El amparo protege el artículo 14, la Sección primera del Capítulo segundo (arts. 15 a 29) y la objeción de conciencia del artículo 30 (arts. 53.2 y 161.1.b).

**12 (a).** «La persona del Rey es inviolable y no está sujeta a responsabilidad». Sus actos se refrendan, y de ellos responden quienes los refrendan (art. 64).

**13 (c).** El mando supremo de las Fuerzas Armadas corresponde al Rey (art. 62.h).

**14 (b).** Las Cortes Generales representan al pueblo español y están formadas por el Congreso de los Diputados y el Senado (art. 66.1).

**15 (b).** La Constitución fija una horquilla de 300 a 400 Diputados (art. 68.1). La cifra de 350 la establece la Ley Orgánica del Régimen Electoral General (art. 162.1), no la Constitución: por eso, si la pregunta dice «según la Constitución», la c) es incorrecta.

**16 (c).** Cuatro Senadores por provincia (art. 69.2), con reglas especiales para las islas, Ceuta y Melilla, y los designados por las Comunidades Autónomas.

**17 (d).** Es la definición de las funciones del Gobierno del artículo 97, que además ejerce la función ejecutiva y la potestad reglamentaria.

**18 (b).** El artículo 104.1 asigna esta misión a las Fuerzas y Cuerpos de Seguridad. Las opciones a) y d) son misiones de las **Fuerzas Armadas** (art. 8.1), una confusión típica.

**19 (c).** Veinte miembros nombrados por el Rey por cinco años: doce entre Jueces y Magistrados, y ocho entre abogados y otros juristas, cuatro a propuesta del Congreso y cuatro del Senado (art. 122.3).

