## La Corona (arts. 56 a 65)

### Quién es el Rey (art. 56)

- Es el **Jefe del Estado**, símbolo de su unidad y permanencia.
- **Arbitra y modera** el funcionamiento regular de las instituciones y asume la más alta representación del Estado en las relaciones internacionales, especialmente con las naciones de su comunidad histórica.
- Su título es el de **Rey de España**, y puede usar los demás que correspondan a la Corona.
- Su persona es **inviolable y no está sujeta a responsabilidad**. Sus actos están **siempre refrendados** (art. 64) y carecen de validez sin ese refrendo, salvo el nombramiento y relevo de los miembros de su Casa (art. 65.2).

### La sucesión (art. 57)

La Corona es hereditaria en los sucesores de Juan Carlos I de Borbón. La sucesión sigue el orden regular de **primogenitura y representación**:

1. Se prefiere **la línea anterior** a las posteriores.
2. En la misma línea, **el grado más próximo** al más remoto.
3. En el mismo grado, **el varón a la mujer**.
4. En el mismo sexo, **la persona de más edad** a la de menos.

Otros datos del artículo 57:

- El heredero tiene la dignidad de **Príncipe de Asturias** y los demás títulos vinculados tradicionalmente al sucesor.
- Si se extinguen todas las líneas llamadas en Derecho, **las Cortes Generales** proveen a la sucesión.
- Quien, con derecho a la sucesión, se case contra la expresa prohibición del Rey y de las Cortes queda excluido, con sus descendientes.
- Las **abdicaciones y renuncias** y las dudas sobre el orden de sucesión se resuelven **por ley orgánica**.

La Reina consorte o el consorte de la Reina no pueden asumir funciones constitucionales, salvo lo dispuesto para la Regencia (art. 58).

