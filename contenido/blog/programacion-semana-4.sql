## El artículo 17, en detalle

Es de los más importantes para esta oposición:

1. **Duración:** la detención preventiva no puede durar más del tiempo estrictamente necesario para las averiguaciones y, **en todo caso, 72 horas**; después, libertad o disposición de la autoridad judicial (17.2).
2. **Información:** el detenido debe ser informado **de forma inmediata y comprensible** de sus derechos y de las razones de la detención, y **no puede ser obligado a declarar** (17.3).
3. **Abogado:** se garantiza su asistencia en las diligencias policiales y judiciales (17.3).
4. ***Habeas corpus*:** procedimiento para poner de inmediato a disposición judicial a toda persona detenida ilegalmente (17.4).

Ojo a la trampa: las 72 horas son un **máximo absoluto**, no un plazo del que se pueda disponer. Si las averiguaciones terminan antes, la detención debe terminar antes.

