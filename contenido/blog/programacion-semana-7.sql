- **Clasificación (arts. 8 y 9)**: divisiones de riesgo del 1.1 al 1.6, y tipos como dinamitas (A), nafos (B), explosivos plásticos (C), hidrogeles (E-a) y emulsiones (E-b), pólvoras y objetos explosivos.
