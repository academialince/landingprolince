## 9. Recursos de alzada y reposición (arts. 112 y 121 a 124)

| Recurso | Contra qué | Ante quién | Plazo (acto expreso) | Plazo para resolver |
|---|---|---|---|---|
| **Alzada** | Actos que **no** ponen fin a la vía administrativa | El **superior jerárquico** (puede presentarse ante el que dictó el acto, que lo remite en diez días) | **Un mes** | **Tres meses** |
| **Reposición** (potestativo) | Actos que **ponen fin** a la vía administrativa | El **mismo órgano** que dictó el acto | **Un mes** | **Un mes** |

