## 1. Quién es interesado (art. 4)

Son interesados: quienes **promueven** el procedimiento como titulares de derechos o intereses legítimos; quienes, sin haberlo iniciado, tienen **derechos** que puedan resultar afectados; y quienes tienen **intereses legítimos** afectados y **se personan** antes de la resolución definitiva. Si la condición deriva de una relación jurídica transmisible, el derechohabiente sucede en ella en cualquier estado del procedimiento.

## 2. Relación electrónica (art. 14)

Las personas físicas **pueden elegir** si se relacionan por medios electrónicos o no, y cambiar de opción en cualquier momento. **Están obligados** al menos: las personas jurídicas; las entidades sin personalidad jurídica; quienes ejercen una profesión con colegiación obligatoria, para los trámites de esa actividad; quienes representan a un obligado; y los **empleados públicos** en los trámites que realicen por su condición de tales. Si un obligado presenta su solicitud en papel, se le requiere para que la subsane por vía electrónica, y cuenta como fecha la de la subsanación (art. 68.4). La solicitud de la oposición, por ejemplo, se presenta por vía electrónica en la Sede Electrónica de la Guardia Civil, en 15 días hábiles (base 3.1; repásalo en el artículo de la [convocatoria de 2026](/blog/convocatoria-guardia-civil-2026-plazas-calendario)).

## 3. Cómo se cuentan los plazos (art. 30)

| Tipo de plazo | Regla |
|---|---|
| **Horas** | Hábiles; de hora en hora y de minuto en minuto; nunca más de 24 (si no, se expresan en días) |
| **Días** | **Hábiles**: se excluyen **sábados, domingos y festivos**, salvo que una ley o el Derecho de la UE digan otra cosa |
| **Inicio** | Desde el **día siguiente** a la notificación o publicación, o al silencio |
| **Meses o años** | Desde el día siguiente, y concluyen **el mismo día** en que se produjo la notificación en el mes o año de vencimiento; si no existe, el **último día del mes** |
| **Último día inhábil** | Se prorroga al **primer día hábil siguiente** |
| **Hábil en un sitio e inhábil en otro** | Se considera **inhábil** en todo caso |

La Administración puede **ampliar** los plazos hasta **la mitad** de su duración, antes de que venzan y sin perjudicar a terceros; un plazo vencido no se amplía (art. 32).

## 4. Obligación de resolver (art. 21)

La Administración debe dictar resolución expresa y notificarla en todos los procedimientos. El plazo máximo lo fija la norma del procedimiento y **no puede exceder de seis meses**, salvo que una ley o el Derecho de la UE prevean uno mayor. Si la norma no fija plazo, es de **tres meses**. Se cuenta desde el acuerdo de iniciación (de oficio) o desde la entrada de la solicitud en el registro electrónico del órgano competente (a solicitud).

## 5. Silencio administrativo (arts. 24 y 25)

**A solicitud del interesado**, el silencio es **estimatorio** como regla general, salvo que una norma con rango de ley, del Derecho de la UE o internacional diga lo contrario. Es **desestimatorio** en:

- el derecho de petición del artículo 29 de la Constitución;
- los procedimientos que transfieran facultades sobre el **dominio público** o el **servicio público**;
- las actividades que puedan **dañar el medio ambiente**;
- la **responsabilidad patrimonial** de las administraciones;
- la **impugnación de actos y disposiciones** y la revisión de oficio a solicitud del interesado. Excepción: si se recurre en alzada una desestimación por silencio y tampoco se resuelve el recurso, este se entiende **estimado**, salvo en las materias anteriores.

La estimación por silencio es un **acto administrativo** finalizador; la desestimación solo permite recurrir. **De oficio** (art. 25), el vencimiento produce desestimación si podían reconocerse derechos y **caducidad** en los procedimientos sancionadores o de gravamen.

## 6. Notificaciones (arts. 40 y 43)

- Se cursan en **diez días** desde que se dicta el acto y contienen el texto íntegro, si pone fin o no a la vía administrativa, los recursos, el órgano y el plazo.
- Las electrónicas se practican al **acceder** a su contenido. Si son obligatorias o el interesado las eligió, se entienden **rechazadas a los diez días naturales** de su puesta a disposición sin acceso.

## 7. Subsanación, trámites y audiencia (arts. 68, 73 y 82)

- **Subsanación:** **diez días**, con advertencia de que, si no se subsana, se tendrá al interesado por **desistido**. Se puede ampliar hasta **cinco días** más, salvo en procedimientos selectivos o de concurrencia competitiva (como una oposición).
- **Trámites del interesado:** diez días, salvo otro plazo (art. 73).
- **Audiencia:** antes de la propuesta de resolución, plazo **no inferior a diez ni superior a quince días**; se puede prescindir de ella si solo se tienen en cuenta los hechos y alegaciones del propio interesado.

