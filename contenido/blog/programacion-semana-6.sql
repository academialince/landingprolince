## La Dirección General de la Guardia Civil (art. 4)

Es el corazón del tema para ti:

- Su titular tiene **rango de subsecretario**.
- Es el órgano encargado de la **ordenación, dirección, coordinación y ejecución** de las misiones de la Guardia Civil, según las directrices de los Ministerios del Interior y de Defensa en sus respectivas competencias.
