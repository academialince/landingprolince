## Preguntas frecuentes

### ¿Cuánto tiempo pueden retenerme para identificarme?

El estrictamente necesario y nunca más de seis horas (art. 16.2 de la LO 4/2015), con libro-registro y volante acreditativo.

### ¿Negarse a identificarse es delito?

Por sí sola, la negativa está tipificada como infracción grave en el art. 36.6 de la LO 4/2015. Puede llegar a ser delito de desobediencia si se cumplen los requisitos del Código Penal; el propio art. 16.5 remite a él.

### ¿Puede un vigilante de seguridad quedarse con mi DNI?

No. Puede pedir la identificación en el acceso e impedir la entrada si te niegas, pero en ningún caso retener la documentación personal (art. 32.1.b de la Ley 5/2014).

### ¿Pueden los vigilantes privados investigar delitos?

No. La investigación privada es exclusiva de los detectives y solo sobre delitos perseguibles a instancia de parte; si conocen un delito perseguible de oficio, deben denunciarlo (arts. 5 y 10 de la Ley 5/2014).

