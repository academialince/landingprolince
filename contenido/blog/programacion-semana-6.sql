### Capítulo I: disposiciones generales

El artículo 1 declara que la seguridad ciudadana es un requisito indispensable para el pleno ejercicio de los derechos fundamentales y las libertades públicas, y que su salvaguarda, como bien jurídico de carácter colectivo, es función del Estado. El artículo 5 enumera las autoridades competentes del Estado (Ministro del Interior, Secretario de Estado de Seguridad, Delegados y Subdelegados del Gobierno, entre otros), y el artículo 7 regula el deber de colaboración de autoridades, particulares y seguridad privada.

### Capítulo II: DNI e identificación

- **Art. 8**: el DNI es el único documento con suficiente valor por sí solo para acreditar la identidad y los datos personales de su titular.
- **Art. 9**: es **obligatorio a partir de los catorce años**, personal e intransferible. Su titular debe exhibirlo cuando lo requieran la autoridad o sus agentes y dar cuenta de su sustracción o extravío «tan pronto como sea posible».
- **Art. 10**: su expedición corresponde al Ministerio del Interior, que la ejerce a través de la **Dirección General de la Policía**.

### Capítulo III: las potestades que más se estudian

**Identificación de personas (art. 16).** Los agentes pueden requerirla en dos supuestos: cuando haya indicios de que la persona ha podido participar en una infracción, o cuando sea razonablemente necesario para prevenir un delito. Si no es posible identificarla por ningún medio (incluida la vía telemática o telefónica) o se niega, pueden requerirle que les acompañe a las dependencias más próximas, a los solos efectos de identificación y por el tiempo estrictamente necesario, **que en ningún caso podrá superar las seis horas**. Detalles que conviene memorizar:

- Se le informa de modo inmediato y comprensible de las razones.
- En las dependencias se lleva un **libro-registro**; el órgano competente remite **mensualmente** al Ministerio Fiscal un extracto de las diligencias, y los asientos se cancelan de oficio **a los tres años**.
- A la salida se entrega un **volante** que acredita el tiempo de permanencia, la causa y la identidad de los agentes.

**Entrada en domicilio (art. 15).** Solo en los casos permitidos por la Constitución y las leyes. Es causa legítima suficiente evitar daños inminentes y graves a personas o cosas en supuestos de catástrofe, calamidad, ruina inminente u otros de extrema y urgente necesidad; después se remite el acta o atestado a la autoridad judicial.

**Otras potestades:**

| Artículo | Potestad | Clave |
|---|---|---|
| 17 | Restricción del tránsito y controles | Por el tiempo imprescindible; controles para delitos de especial gravedad o que generen alarma social |
| 18 | Comprobaciones y registros en lugares públicos | Para impedir el porte ilegal de armas, explosivos u objetos peligrosos |
| 19 | Disposiciones comunes | Estas diligencias **no están sujetas a las formalidades de la detención** |
| 20 | Registro corporal externo | Agente del mismo sexo y lugar reservado si hay que descubrir partes del cuerpo, salvo urgencia por riesgo grave e inminente |
| 21 | Medidas extraordinarias | Cierre, desalojo o evacuación en emergencias; los agentes pueden adoptarlas por orden verbal si la urgencia lo exige |
| 23 | Reuniones y manifestaciones | Medidas graduales y proporcionadas; la **disolución es el último recurso** y exige aviso previo, salvo alteración con armas u objetos peligrosos |

### Capítulo IV: policía administrativa especial

Los artículos 25 a 29 regulan las obligaciones de registro documental de ciertas actividades, los establecimientos obligados a adoptar medidas de seguridad, los espectáculos y actividades recreativas y el control administrativo de **armas, explosivos, cartuchería y artículos pirotécnicos** (art. 28), que enlaza con el tema 22.

### Capítulo V: régimen sancionador

| Infracción | Multa (art. 39) | Prescribe la infracción (art. 38) | Prescribe la sanción (art. 40) |
|---|---|---|---|
| Leve | 100 a 600 euros | 6 meses | 1 año |
| Grave | 601 a 30.000 euros | 1 año | 2 años |
| Muy grave | 30.001 a 600.000 euros | 2 años | 3 años |

Las graves y muy graves se dividen, además, en grados mínimo, medio y máximo (art. 39.1).

Ejemplos de cada tipo (arts. 35 a 37):

- **Muy grave**: proyectar haces de luz sobre pilotos o conductores de medios de transporte que puedan deslumbrarles y provocar accidentes (art. 35.4).
- **Grave**: la desobediencia o resistencia a la autoridad o a sus agentes que no sea delito, y también **la negativa a identificarse** o dar datos falsos (art. 36.6); el consumo o la tenencia ilícitos de drogas en lugares públicos (art. 36.16).
- **Leve**: las faltas de respeto a un agente en el ejercicio de sus funciones que no sean infracción penal (art. 37.4); la tercera y posteriores pérdidas de la documentación personal en un año (art. 37.11).

Quién sanciona en la Administración del Estado (art. 32): el Ministro del Interior, las muy graves en grado máximo; el Secretario de Estado de Seguridad, las muy graves en grado medio y mínimo; los Delegados del Gobierno, las graves y leves. El procedimiento caduca al año de su incoación sin resolución notificada (art. 50), y el **procedimiento abreviado** (art. 54) permite, en graves y leves, pagar en **quince días** con una **reducción del 50 %**.

Un matiz: el Tribunal Constitucional (sentencia 172/2020) anuló un inciso del artículo 36.23, sobre el uso de imágenes de agentes. Estudia siempre el texto consolidado, que lo advierte.

