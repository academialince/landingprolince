- **Órganos (art. 10):** el **Comité de Ministros** y la **Asamblea** (en el texto, «Asamblea Consultiva»), asistidos por la **Secretaría**.
- **Sede (art. 11):** **Estrasburgo**. **Lenguas oficiales (art. 12):** francés e inglés.
