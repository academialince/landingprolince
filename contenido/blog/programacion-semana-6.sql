## Lo esencial de la Ley 5/2014

- **Fines (art. 4)**: satisfacer las necesidades legítimas de seguridad o de información de los usuarios, contribuir a garantizar la seguridad pública y **complementar el monopolio de la seguridad que corresponde al Estado**.
- **Actividades (art. 5)**: ocho, de la a) a la h): vigilancia y protección; acompañamiento y protección de personas; depósito y custodia de valores; depósito y custodia de explosivos, armas y objetos peligrosos; transporte de esos objetos; instalación y mantenimiento de sistemas conectados a centrales; explotación de centrales de alarmas; e **investigación privada**. Las siete primeras solo las prestan empresas de seguridad; la investigación privada, con carácter exclusivo y excluyente, los despachos de detectives.
- **Principios rectores (art. 8)**: colaboración con las Fuerzas y Cuerpos de Seguridad y prohibición de intervenir en reuniones, manifestaciones o conflictos políticos o laborales, y de controlar opiniones políticas, sindicales o religiosas.
- **Prohibiciones (art. 10)**: los detectives no pueden investigar delitos perseguibles de oficio y deben denunciarlos de inmediato.
- **Personal (art. 26)**: vigilantes de seguridad (y su especialidad, vigilantes de explosivos), escoltas privados, guardas rurales (y sus especialidades, guardas de caza y guardapescas marítimos), jefes de seguridad, directores de seguridad y detectives privados.
- **Requisitos (art. 28)**: entre otros, mayoría de edad y carecer de antecedentes penales por delitos dolosos.
- **Principios de actuación (art. 30)**: legalidad, integridad, dignidad, corrección en el trato, congruencia, proporcionalidad, reserva profesional y colaboración con las Fuerzas y Cuerpos de Seguridad.
- **Protección jurídica (art. 31)**: las agresiones y desobediencias al personal de seguridad privada, debidamente identificado, que actúe en cooperación y bajo el mando de las Fuerzas y Cuerpos de Seguridad se consideran cometidas contra agentes de la autoridad.
- **Vigilantes (art. 32)**: pueden hacer controles de identidad y de objetos en el acceso a los inmuebles que protegen e impedir la entrada a quien se niegue, pero **nunca retener la documentación personal**.

## Caso práctico (hipotético)

Una patrulla requiere a un joven que estaba junto a un vehículo forzado para que se identifique. No lleva DNI, no recuerda el número y se niega a dar sus datos. ¿Qué pueden hacer los agentes?

1. Concurre el supuesto del art. 16.1.a: hay indicios de participación en una infracción.
2. Intentan la identificación por cualquier medio, incluida la consulta telemática.
3. Si no es posible, le requieren para que les acompañe a las dependencias más próximas, informándole de las razones.
4. Permanece el tiempo imprescindible, nunca más de seis horas; se anota en el libro-registro y se le entrega el volante al salir.
5. Su negativa puede constituir la infracción grave del art. 36.6, o un delito de desobediencia si concurren sus requisitos.

Esta diligencia no es una detención (art. 19.1). Compárala con los plazos de [detención y habeas corpus](/blog/detencion-y-habeas-corpus-los-plazos-que-caen-siempre) y con el marco de los [derechos fundamentales](/blog/derechos-fundamentales-libertades-publicas-guardia-civil).

## Errores frecuentes

- Confundir la **prescripción de la infracción** (6 meses, 1 y 2 años) con la **de la sanción** (1, 2 y 3 años).
- Pensar que el traslado para identificar es una detención o que puede durar 24 horas.
- Atribuir la expedición del DNI a la Guardia Civil: corresponde a la Dirección General de la Policía.
- Creer que los detectives pueden investigar cualquier delito: solo los perseguibles a instancia de parte.

