## Errores frecuentes

- **Planificar la semana ideal en lugar de la real.** Si tu trabajo cambia cada semana, tu plan también.
- **Compensar un mal día con una paliza al siguiente.** Rompe el descanso y aumenta el riesgo de lesión.
