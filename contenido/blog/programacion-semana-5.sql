## El Poder Judicial (Título VI, arts. 117 a 127)

**Principios (art. 117):** la justicia **emana del pueblo** y se administra **en nombre del Rey** por Jueces y Magistrados **independientes, inamovibles, responsables y sometidos únicamente al imperio de la ley**. La potestad jurisdiccional (juzgar y hacer ejecutar lo juzgado) corresponde exclusivamente a los Juzgados y Tribunales. Se prohíben los **tribunales de excepción**, y el **principio de unidad jurisdiccional** es la base de su organización; la jurisdicción militar se limita al ámbito estrictamente castrense y al estado de sitio.

Otros principios que se preguntan:

- Es obligado **cumplir las sentencias** y resoluciones firmes (118).
- La justicia es **gratuita** cuando lo disponga la ley y, en todo caso, para quien acredite insuficiencia de recursos (119).
- Las actuaciones judiciales son **públicas**; el procedimiento es predominantemente **oral**, sobre todo en lo criminal, y las sentencias son **motivadas** (120).
- Los daños por **error judicial** o funcionamiento anormal de la justicia dan derecho a indemnización a cargo del Estado (121).
- Los ciudadanos pueden ejercer la **acción popular** y participar mediante el **jurado** (125).
- Jueces, Magistrados y Fiscales en activo no pueden desempeñar otros cargos públicos ni pertenecer a **partidos políticos o sindicatos** (127).

