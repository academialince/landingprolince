## El Gobierno (Título IV, arts. 97 a 107)

**Función (art. 97):** dirige la política interior y exterior, la Administración civil y militar y la defensa del Estado; ejerce la **función ejecutiva** y la **potestad reglamentaria**.

**Composición (art. 98):** Presidente, Vicepresidentes (en su caso), Ministros y los demás miembros que establezca la ley. El Presidente **dirige la acción del Gobierno y coordina** a los demás miembros, sin perjuicio de su responsabilidad directa.

### La investidura (art. 99)

1. Tras cada renovación del Congreso, el Rey, previa consulta con los representantes de los grupos políticos con representación parlamentaria y **a través del Presidente del Congreso**, propone un candidato.
2. El candidato expone su programa y solicita la confianza del Congreso.
3. **Primera votación:** hace falta **mayoría absoluta**. Si no se alcanza, nueva votación **48 horas después**, en la que basta la **mayoría simple**.
4. Si no se otorga la confianza, se tramitan sucesivas propuestas.
5. Si pasan **dos meses desde la primera votación** sin que ningún candidato obtenga la confianza, el Rey **disuelve ambas Cámaras** y convoca elecciones, con el refrendo del Presidente del Congreso.

Los demás miembros del Gobierno los nombra y separa el Rey a propuesta del Presidente (art. 100).

### Cese y responsabilidad

- **Cese (art. 101):** tras la celebración de elecciones generales, en los casos de pérdida de la confianza parlamentaria, o por dimisión o fallecimiento del Presidente. El Gobierno cesante sigue **en funciones** hasta que toma posesión el nuevo.
- **Responsabilidad criminal (art. 102):** ante la **Sala de lo Penal del Tribunal Supremo**. Si la acusación es por **traición** o por delito contra la seguridad del Estado en el ejercicio de sus funciones, solo puede plantearla **una cuarta parte del Congreso** y aprobarla su **mayoría absoluta**. En estos casos no cabe el derecho de gracia.

### La Administración y las Fuerzas y Cuerpos de Seguridad

- **Administración Pública (art. 103):** sirve con **objetividad** los intereses generales y actúa según los principios de **eficacia, jerarquía, descentralización, desconcentración y coordinación**, con sometimiento pleno a la ley y al Derecho. El acceso a la función pública se rige por los principios de **mérito y capacidad**.
- **Fuerzas y Cuerpos de Seguridad (art. 104):** bajo la dependencia del Gobierno, su misión es **proteger el libre ejercicio de los derechos y libertades y garantizar la seguridad ciudadana**. Una ley orgánica determinará sus funciones, principios básicos de actuación y estatutos. Es el artículo que define tu futura profesión.
- **Consejo de Estado (art. 107):** supremo órgano consultivo del Gobierno.

## Relaciones entre el Gobierno y las Cortes (Título V, arts. 108 a 116)

El Gobierno **responde solidariamente** en su gestión política **ante el Congreso** (art. 108).

| Instrumento | Quién lo inicia | Requisitos | Consecuencia |
|---|---|---|---|
| **Cuestión de confianza** (112) | El Presidente, previa deliberación del Consejo de Ministros | Sobre su programa o una declaración de política general; se otorga por **mayoría simple** | Si se niega, el Gobierno dimite y se abre una nueva investidura (114.1) |
| **Moción de censura** (113) | Al menos **una décima parte de los Diputados** | Debe incluir un **candidato**; no se vota hasta pasados **cinco días**; mociones alternativas en los **dos primeros**; se aprueba por **mayoría absoluta** | Si prospera, el candidato queda investido y el Rey lo nombra (114.2). Si fracasa, sus firmantes no pueden presentar otra en el mismo periodo de sesiones |
| **Disolución** (115) | El Presidente, previa deliberación del Consejo de Ministros y bajo su exclusiva responsabilidad | No mientras esté en trámite una moción de censura; no antes de **un año** desde la anterior (salvo la del 99.5) | El decreto fija la fecha de las elecciones |

**Estados excepcionales (art. 116):** el de **alarma** lo declara el Gobierno por un máximo de **15 días**, dando cuenta al Congreso, que debe autorizar la prórroga; el de **excepción**, el Gobierno con **autorización previa del Congreso**, por un máximo de **30 días** prorrogables por otros 30; el de **sitio**, el Congreso por **mayoría absoluta**, a propuesta exclusiva del Gobierno.

## El Poder Judicial (Título VI, arts. 117 a 127)

**Principios (art. 117):** la justicia **emana del pueblo** y se administra **en nombre del Rey** por Jueces y Magistrados **independientes, inamovibles, responsables y sometidos únicamente al imperio de la ley**. La potestad jurisdiccional (juzgar y hacer ejecutar lo juzgado) corresponde exclusivamente a los Juzgados y Tribunales. Se prohíben los **tribunales de excepción**, y el **principio de unidad jurisdiccional** es la base de su organización; la jurisdicción militar se limita al ámbito estrictamente castrense y al estado de sitio.

Otros principios que se preguntan:

- Es obligado **cumplir las sentencias** y resoluciones firmes (118).
- La justicia es **gratuita** cuando lo disponga la ley y, en todo caso, para quien acredite insuficiencia de recursos (119).
- Las actuaciones judiciales son **públicas**; el procedimiento es predominantemente **oral**, sobre todo en lo criminal, y las sentencias son **motivadas** (120).
- Los daños por **error judicial** o funcionamiento anormal de la justicia dan derecho a indemnización a cargo del Estado (121).
- Los ciudadanos pueden ejercer la **acción popular** y participar mediante el **jurado** (125).
- Jueces, Magistrados y Fiscales en activo no pueden desempeñar otros cargos públicos ni pertenecer a **partidos políticos o sindicatos** (127).

### El Consejo General del Poder Judicial (art. 122)

Es el **órgano de gobierno** del poder judicial.

| Elemento | Dato |
|---|---|
| Presidente | El del Tribunal Supremo |
| Miembros nombrados por el Rey | 20 |
| Duración del mandato | 5 años |
| Entre Jueces y Magistrados | 12, en los términos de la ley orgánica |
| Entre abogados y otros juristas | 8: 4 a propuesta del Congreso y 4 del Senado, por **mayoría de tres quintos** |

Los juristas deben ser de reconocida competencia y con **más de quince años** de ejercicio profesional.

### Otras instituciones del Título VI

- **Tribunal Supremo (art. 123):** jurisdicción en toda España; órgano superior en todos los órdenes, salvo en materia de garantías constitucionales. Su Presidente lo nombra el Rey **a propuesta del CGPJ**.
- **Ministerio Fiscal (art. 124):** promueve la acción de la justicia en defensa de la legalidad, de los derechos de los ciudadanos y del interés público. Actúa según los principios de **unidad de actuación y dependencia jerárquica**, con sujeción a los de **legalidad e imparcialidad**. El **Fiscal General del Estado** lo nombra el Rey **a propuesta del Gobierno, oído el CGPJ**.
- **Policía judicial (art. 126):** depende de los Jueces, de los Tribunales y del Ministerio Fiscal en sus funciones de **averiguación del delito y descubrimiento y aseguramiento del delincuente**. Aquí aparece la Guardia Civil en su faceta de policía judicial.

## El Tribunal Constitucional (Título IX, arts. 159 a 165)

| Elemento | Dato |
|---|---|
| Miembros | 12, nombrados por el Rey |
| A propuesta del Congreso | 4 (mayoría de tres quintos) |
| A propuesta del Senado | 4 (misma mayoría) |
| A propuesta del Gobierno | 2 |
| A propuesta del CGPJ | 2 |
| Mandato | 9 años, renovación por terceras partes cada 3 |
| Presidente | Nombrado por el Rey entre sus miembros, a propuesta del Pleno, por 3 años (art. 160) |

Son Magistrados y Fiscales, Profesores de Universidad, funcionarios públicos y Abogados, todos **juristas de reconocida competencia con más de quince años de ejercicio profesional**. Su condición es incompatible con todo mandato representativo, cargos políticos o administrativos, funciones directivas en partidos o sindicatos, las carreras judicial y fiscal y cualquier actividad profesional o mercantil (159.4). La Ley Orgánica añade que el Tribunal tiene **dos Salas de seis Magistrados** cada una.

### Competencias (art. 161)

- **Recurso de inconstitucionalidad** contra leyes y disposiciones normativas con fuerza de ley.
- **Recurso de amparo** por violación de los derechos del artículo 53.2 (art. 14, arts. 15 a 29 y objeción de conciencia).
- **Conflictos de competencia** entre el Estado y las Comunidades Autónomas, o de estas entre sí.
- Las demás materias que le atribuyan la Constitución o las leyes orgánicas.
- Además, el **Gobierno** puede impugnar disposiciones y resoluciones de las Comunidades Autónomas, lo que produce su **suspensión**, que el Tribunal debe ratificar o levantar en **cinco meses** como máximo (161.2).

### Legitimación (art. 162)

| Recurso | Legitimados |
|---|---|
| Inconstitucionalidad | Presidente del Gobierno, Defensor del Pueblo, **50 Diputados**, **50 Senadores**, órganos colegiados ejecutivos de las Comunidades Autónomas y, en su caso, sus Asambleas |
| Amparo | Toda persona natural o jurídica con **interés legítimo**, el **Defensor del Pueblo** y el **Ministerio Fiscal** |

**Plazos de la Ley Orgánica del Tribunal Constitucional:** **tres meses** para el recurso de inconstitucionalidad desde la publicación de la norma (art. 33); **veinte días** para el amparo frente a actos del Gobierno o de sus autoridades, una vez agotada la vía judicial (art. 43); y **treinta días** frente a resoluciones judiciales (art. 44).

**Efectos (art. 164):** las sentencias se publican en el BOE con los votos particulares, tienen valor de **cosa juzgada** desde el día siguiente a su publicación y **no cabe recurso** contra ellas.

## Casos prácticos (hipotéticos)

**Caso 1.** Un candidato obtiene 170 votos a favor y 175 en contra en la primera votación de investidura. ¿Qué pasa? *Solución:* no alcanza la mayoría absoluta. Se repite la votación 48 horas después; si entonces tiene más síes que noes, queda investido por mayoría simple.

**Caso 2.** Un grupo de 30 diputados quiere presentar una moción de censura. *Solución:* con un Congreso de 350 miembros, la décima parte son 35. Treinta no bastan.

**Caso 3.** Un guardia civil detenido considera vulnerado su derecho a la libertad (art. 17) por una resolución judicial. *Solución:* tras agotar la vía judicial, puede acudir en amparo al Tribunal Constitucional en el plazo de treinta días.

## Errores frecuentes

- **Confundir CGPJ y Tribunal Constitucional:** 20 miembros y 5 años frente a 12 miembros y 9 años.
