- **Ciudadanía (art. 20 TFUE):** la tiene toda persona con la nacionalidad de un Estado miembro; **se añade a la nacional sin sustituirla**. Incluye circular y residir libremente, votar y ser elegido en las elecciones europeas y municipales del Estado de residencia y la protección consular de cualquier Estado miembro en un tercer país.
- **Título V del TFUE (arts. 67 a 89):** ausencia de controles en las fronteras interiores, política común de asilo, inmigración y control de fronteras exteriores (art. 77), cooperación judicial penal con **Eurojust** (art. 85) y cooperación policial con **Europol** (art. 88). Es la parte del Derecho de la UE más cercana al trabajo de un guardia civil.

