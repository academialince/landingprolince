## Preguntas frecuentes

### ¿Cuántas instituciones tiene la Unión Europea?
Siete, enumeradas en el artículo 13.1 del TUE. El Comité Económico y Social y el Comité de las Regiones son órganos consultivos.

### ¿Cuántos diputados tiene el Parlamento Europeo?
El Tratado fija un máximo de 750 más el Presidente. En la legislatura 2024-2029 son 720, 61 de ellos elegidos en España.

### ¿Cuánto dura el mandato de la Comisión y del Parlamento?
Cinco años en ambos casos (arts. 17.3 y 14.3 TUE).

### ¿Qué diferencia hay entre reglamento y directiva?
El reglamento es directamente aplicable y obligatorio en todos sus elementos; la directiva obliga en cuanto al resultado y deja a los Estados la forma y los medios.

### ¿Qué valor tiene la Carta de los Derechos Fundamentales de la UE?
El mismo valor jurídico que los Tratados (art. 6.1 TUE).

