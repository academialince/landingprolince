## Su peso en España: los artículos 10.2 y 96.1 de la Constitución

- **Artículo 10.2:** las normas relativas a los derechos fundamentales y a las libertades que la Constitución reconoce se interpretarán **de conformidad con la Declaración Universal de Derechos Humanos y los tratados y acuerdos internacionales sobre las mismas materias ratificados por España**.
- **Artículo 96.1:** los tratados internacionales válidamente celebrados, una vez publicados oficialmente en España, **forman parte del ordenamiento interno**.

Fíjate en el detalle: la Constitución cita la Declaración Universal **por su nombre**, mientras que al resto de textos se refiere de forma genérica como tratados ratificados por España. Por eso este tema enlaza con los [derechos fundamentales del Título I](/blog/derechos-fundamentales-libertades-publicas-guardia-civil) y con el resto de [la Constitución](/blog/constitucion-oposicion-guardia-civil).

## El Convenio Europeo de Derechos Humanos

