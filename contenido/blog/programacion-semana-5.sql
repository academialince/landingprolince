## Título Preliminar: las normas jurídicas

### Fuentes del ordenamiento (art. 1)
- Son **la ley, la costumbre y los principios generales del derecho**, por este orden.
- Carecen de validez las disposiciones que contradigan otra de **rango superior** (jerarquía).
- La **costumbre** solo rige en defecto de ley aplicable, si no es contraria a la moral o al orden público y resulta probada.
- Los **principios generales** se aplican en defecto de ley o costumbre, sin perjuicio de su carácter informador.
- Los **tratados internacionales** no son de aplicación directa en España mientras no se publiquen íntegramente en el BOE.
- La **jurisprudencia** no es fuente: **complementa** el ordenamiento con la doctrina reiterada del Tribunal Supremo.

### Vigencia de las leyes (art. 2)
- Entran en vigor a los **veinte días** de su completa publicación en el BOE, si no disponen otra cosa (*vacatio legis*).
- Solo se derogan por otras posteriores; la simple derogación **no hace revivir** las leyes que la derogada hubiera derogado.
- **No tienen efecto retroactivo** si no disponen lo contrario.

