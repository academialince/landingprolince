| **Opción** | Quien esté o haya estado sujeto a la patria potestad de un español, entre otros; caduca a los veinte años de edad, con matices | 20 |
| **Carta de naturaleza** | Otorgada discrecionalmente por **Real Decreto** por circunstancias excepcionales | 21.1 |
| **Residencia** | Concesión del **Ministro de Justicia**, que puede denegarla por orden público o interés nacional | 21.2 y 22 |

**Plazos de residencia (art. 22):** **diez años** con carácter general; **cinco** para refugiados; **dos** para nacionales de origen de países iberoamericanos, Andorra, Filipinas, Guinea Ecuatorial o Portugal, y sefardíes; **un año** para, entre otros, el nacido en territorio español, el casado desde hace un año con española o español sin separación o el viudo de español. La residencia debe ser **legal, continuada e inmediatamente anterior** a la petición, y se exige buena conducta cívica y suficiente integración.

**Requisitos comunes (art. 23):** que el mayor de catorce años jure o prometa **fidelidad al Rey y obediencia a la Constitución y a las leyes**; que renuncie a su nacionalidad anterior (salvo los naturales de los países del artículo 24.1 y los sefardíes originarios de España); e inscribir la adquisición en el Registro Civil. Las concesiones caducan si no se cumplen estos requisitos en **ciento ochenta días** desde la notificación (art. 21.4).

**Pérdida (arts. 24 y 25):** ningún español de origen puede ser privado de su nacionalidad (art. 11.2 CE), aunque puede perderla en supuestos voluntarios; quien no es de origen la pierde, por ejemplo, si durante **tres años** usa solo la nacionalidad a la que renunció.

