## Errores frecuentes

- **Poner la jurisprudencia como fuente del Derecho:** complementa el ordenamiento, pero el artículo 1.1 solo cita ley, costumbre y principios generales.
- **Confundir el cómputo civil con el administrativo:** en el civil no se excluyen los días inhábiles (art. 5.2); en la Ley 39/2015, sí.
