### Su relación con España

Desde 1979, una persona que considere que España ha vulnerado un derecho del Convenio puede acudir a Estrasburgo **después** de agotar la vía interna, lo que en materia de derechos fundamentales suele incluir el recurso de amparo ante el Tribunal Constitucional. El Tribunal Europeo no es una «tercera instancia» que revise los hechos: comprueba si el Estado ha respetado el Convenio.

