## Libro I: de las personas

### Nacionalidad (Título I)

| Vía | Requisito | Artículo |
|---|---|---|
| **Origen** | Hijo de padre o madre españoles; nacido en España de padres extranjeros si uno de ellos nació también en España (salvo hijos de diplomáticos); nacido en España de padres apátridas o sin nacionalidad atribuible; nacido en España con filiación no determinada | 17 |
| **Adopción** | El extranjero menor de dieciocho años adoptado por español adquiere la nacionalidad de origen | 19 |
| **Opción** | Quien esté o haya estado sujeto a la patria potestad de un español, entre otros; caduca a los veinte años de edad, con matices | 20 |
| **Carta de naturaleza** | Otorgada discrecionalmente por **Real Decreto** por circunstancias excepcionales | 21.1 |
| **Residencia** | Concesión del **Ministro de Justicia**, que puede denegarla por orden público o interés nacional | 21.2 y 22 |

**Plazos de residencia (art. 22):** **diez años** con carácter general; **cinco** para refugiados; **dos** para nacionales de origen de países iberoamericanos, Andorra, Filipinas, Guinea Ecuatorial o Portugal, y sefardíes; **un año** para, entre otros, el nacido en territorio español, el casado desde hace un año con española o español sin separación o el viudo de español. La residencia debe ser **legal, continuada e inmediatamente anterior** a la petición, y se exige buena conducta cívica y suficiente integración.

**Requisitos comunes (art. 23):** que el mayor de catorce años jure o prometa **fidelidad al Rey y obediencia a la Constitución y a las leyes**; que renuncie a su nacionalidad anterior (salvo los naturales de los países del artículo 24.1 y los sefardíes originarios de España); e inscribir la adquisición en el Registro Civil. Las concesiones caducan si no se cumplen estos requisitos en **ciento ochenta días** desde la notificación (art. 21.4).

**Pérdida (arts. 24 y 25):** ningún español de origen puede ser privado de su nacionalidad (art. 11.2 CE), aunque puede perderla en supuestos voluntarios; quien no es de origen la pierde, por ejemplo, si durante **tres años** usa solo la nacionalidad a la que renunció.

### Personalidad (Título II)
- **Art. 29:** el nacimiento determina la personalidad, pero el **concebido se tiene por nacido** para todos los efectos que le sean favorables.
- **Art. 30:** la personalidad se adquiere en el momento del nacimiento **con vida**, una vez producido el **entero desprendimiento del seno materno**.
- **Art. 32:** se extingue por la **muerte**.

### Domicilio (Título III, art. 40)
Es el lugar de **residencia habitual**. El de los diplomáticos con derecho de extraterritorialidad es el último que tuvieron en España.

### Matrimonio (Título IV)
- **Art. 44:** mismos requisitos y efectos si los contrayentes son del mismo o de distinto sexo.
- **Art. 45:** no hay matrimonio sin consentimiento matrimonial.
- **Art. 46:** no pueden casarse los **menores de edad no emancipados** ni quienes ya estén casados.
- **Art. 47:** tampoco entre sí los parientes en línea recta por consanguinidad o adopción, los colaterales por consanguinidad **hasta el tercer grado** y los condenados por participar en la **muerte dolosa** del cónyuge o pareja.
- **Art. 48:** el juez puede **dispensar** dos impedimentos: el de muerte dolosa y el de parentesco de **tercer grado** entre colaterales.

### Filiación y alimentos (Títulos V y VI)
- **Art. 108:** la filiación puede ser por naturaleza (matrimonial o no matrimonial) y por adopción, y todas **surten los mismos efectos**.
- **Art. 142:** los alimentos comprenden sustento, habitación, vestido, asistencia médica y la educación del alimentista mientras sea menor (y después, si no ha terminado su formación por causa no imputable).

### Patria potestad, tutela, mayoría de edad y apoyos (Títulos VII, IX a XI)
- **Patria potestad (art. 154):** los hijos no emancipados están bajo la patria potestad de los progenitores, que se ejerce **en interés de los hijos** y comprende velar por ellos, educarlos, representarlos y administrar sus bienes.
- **Tutela de menores (art. 199):** los menores no emancipados en situación de desamparo y los no sujetos a patria potestad. Desde 2021, la tutela queda **solo para menores**.
- **Emancipación (art. 239):** por la mayor edad, por concesión de quienes ejerzan la patria potestad o por concesión judicial.
- **Mayor edad (art. 240):** a los **dieciocho años cumplidos**, contando **completo el día del nacimiento**. Coincide con el artículo 12 de la Constitución.
- **Emancipación por concesión (art. 241):** exige **dieciséis años** cumplidos y que el menor la consienta; se otorga por escritura pública o ante el encargado del Registro Civil.
- **Apoyos (art. 250):** además de las medidas voluntarias, la **guarda de hecho** (informal), la **curatela** (apoyo continuado, fijado por el juez) y el **defensor judicial** (apoyo ocasional).

## Casos prácticos (hipotéticos)

1. **Una ley publicada el 1 de marzo que no dice nada sobre su entrada en vigor.** Entra en vigor a los veinte días de su publicación completa en el BOE (art. 2.1).
2. **Lucía, peruana, lleva dos años de residencia legal y continuada en España.** Puede solicitar la nacionalidad por residencia, porque Perú es un país iberoamericano (art. 22.1); deberá jurar o prometer fidelidad al Rey y obediencia a la Constitución, pero no tendrá que renunciar a la peruana (art. 23.b en relación con el 24.1).
3. **Un chico de diecisiete años quiere casarse.** No puede si no está emancipado (art. 46.1.º); si sus padres le concedieron la emancipación al cumplir dieciséis años, sí.

## Errores frecuentes

- **Poner la jurisprudencia como fuente del Derecho:** complementa el ordenamiento, pero el artículo 1.1 solo cita ley, costumbre y principios generales.
- **Confundir el cómputo civil con el administrativo:** en el civil no se excluyen los días inhábiles (art. 5.2); en la Ley 39/2015, sí.
- **Hablar de «incapacitación» o de tutela de adultos:** desde 2021 hay medidas de apoyo y la tutela es solo para menores.
- **Equivocar los plazos de residencia:** 10, 5, 2 y 1 años, cada uno con su colectivo.
- **Pensar que todo impedimento es dispensable:** solo lo son la muerte dolosa del cónyuge y el tercer grado colateral.

