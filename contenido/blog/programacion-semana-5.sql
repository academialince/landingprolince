## Detalles que se confunden

- **Consejo Europeo no es el Consejo.** El primero reúne a jefes de Estado o de Gobierno y no legisla; el segundo reúne a ministros y legisla con el Parlamento. Y ninguno de los dos es el **Consejo de Europa**, que es otra organización.
- **Presidente del Consejo Europeo (art. 15.5):** elegido por mayoría cualificada para **dos años y medio**, renovable **una sola vez**; no puede ejercer mandato nacional.
- **Mayoría cualificada (art. 16.4):** al menos el **55 % de los miembros del Consejo**, con un mínimo de **quince**, que representen al menos el **65 % de la población**. La minoría de bloqueo exige **al menos cuatro** miembros.
- **Presidencia del Consejo:** rota entre los Estados en sus formaciones, salvo la de **Asuntos Exteriores**, que preside el Alto Representante (arts. 16.9 y 18.3).
- **Composición de la Comisión (art. 17.5):** el Tratado prevé dos tercios del número de Estados, salvo que el Consejo Europeo decida otra cosa por unanimidad. Lo decidió: la [Decisión 2013/272/UE](https://eur-lex.europa.eu/eli/dec/2013/272/oj) mantiene **un miembro por Estado**, incluidos el Presidente y el Alto Representante.
- **Elección del Presidente de la Comisión (art. 17.7):** lo propone el Consejo Europeo por mayoría cualificada, teniendo en cuenta las elecciones europeas, y lo elige el Parlamento por **mayoría de sus miembros**. Después, el colegio entero se somete al voto de aprobación del Parlamento y lo nombra el Consejo Europeo.
- **Moción de censura (art. 17.8):** el Parlamento puede votarla contra la Comisión; si prospera, dimiten colectivamente sus miembros.
- **Alto Representante (art. 18):** nombrado por el Consejo Europeo por mayoría cualificada con la aprobación del Presidente de la Comisión; dirige la política exterior y de seguridad común y es Vicepresidente de la Comisión.

