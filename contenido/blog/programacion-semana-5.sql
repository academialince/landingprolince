- **Patria potestad (art. 154):** los hijos no emancipados están bajo la patria potestad de los progenitores, que se ejerce **en interés de los hijos** y comprende velar por ellos, educarlos, representarlos y administrar sus bienes.
- **Tutela de menores (art. 199):** los menores no emancipados en situación de desamparo y los no sujetos a patria potestad. Desde 2021, la tutela queda **solo para menores**.
- **Emancipación (art. 239):** por la mayor edad, por concesión de quienes ejerzan la patria potestad o por concesión judicial.
- **Mayor edad (art. 240):** a los **dieciocho años cumplidos**, contando **completo el día del nacimiento**. Coincide con el artículo 12 de la Constitución.
