El **procedimiento legislativo ordinario** es la adopción conjunta por el Parlamento y el Consejo, a propuesta de la Comisión, de un reglamento, una directiva o una decisión (arts. 289 y 294 TFUE). Y si la Comisión estima que un Estado ha incumplido sus obligaciones, emite un dictamen motivado y, si no se atiene a él, puede recurrir al Tribunal de Justicia (art. 258 TFUE).

## Un caso práctico (hipotético)

España debe adaptar su normativa a una nueva directiva sobre protección de datos en investigaciones penales y a un nuevo reglamento sobre armas de fuego. La **directiva** solo fija el resultado y exige una ley española de transposición; el **reglamento** se aplica directamente desde su entrada en vigor, sin necesidad de ley nacional. Si España no transpone la directiva en plazo, la Comisión puede abrir un procedimiento de incumplimiento (art. 258 TFUE).

## Errores frecuentes

- Contar como instituciones al **Comité Económico y Social** o al **Comité de las Regiones**.
- Atribuir funciones legislativas al **Consejo Europeo**.
- Decir que la Comisión tiene «dos tercios de comisarios»: el Tratado lo permite, pero hoy rige un miembro por Estado.
- Confundir **750** (techo del Tratado) con **720** (reparto 2024-2029).
- Pensar que la directiva es «directamente aplicable»: lo es el reglamento.

