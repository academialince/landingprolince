## La Declaración Universal de Derechos Humanos

- **Qué es:** una declaración proclamada por la **Asamblea General de las Naciones Unidas** en **París, el 10 de diciembre de 1948**, mediante la **Resolución 217 A (III)**, según la [página oficial de la ONU](https://www.un.org/es/about-us/universal-declaration-of-human-rights).
- **Extensión:** un preámbulo y **30 artículos**.
- **Naturaleza:** es una **resolución de la Asamblea General**, no un tratado. Su fuerza en España le llega, sobre todo, por el artículo 10.2 de la Constitución.
- **Idea central:** todos los seres humanos **nacen libres e iguales en dignidad y derechos** (art. 1), y los derechos corresponden a todas las personas sin distinción alguna (art. 2).

