### Legitimación (art. 162)

| Recurso | Legitimados |
|---|---|
| Inconstitucionalidad | Presidente del Gobierno, Defensor del Pueblo, **50 Diputados**, **50 Senadores**, órganos colegiados ejecutivos de las Comunidades Autónomas y, en su caso, sus Asambleas |
